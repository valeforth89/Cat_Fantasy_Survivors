def orbit(n, d, **k): return _mk("orbit", n, d, **k)
def heal(n, d, **k): return _mk("heal", n, d, **k)
def buff(n, d, **k): return _mk("buff", n, d, **k)
def summon(n, d, **k): return _mk("summon", n, d, **k)


