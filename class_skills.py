def class_actives(cid, n_total=10):
    """Lista de especificações (sem id/unlock) das ativas da classe, na ordem de desbloqueio."""
    c = CLASSES[cid]
    dt = "mag" if c["attr"] == "int" else "phys"
    out = []
    for sp in KITS.get(cid, []):
        sp = dict(sp)
        sp.setdefault("dmgtype", dt)
        sp.setdefault("dmg", 10)   # valor provisório: o balance.py calcula o dano real
        out.append(sp)
    return out[:n_total]
